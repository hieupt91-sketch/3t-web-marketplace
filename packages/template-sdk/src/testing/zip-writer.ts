import { crc32, deflateRawSync } from 'node:zlib';

/**
 * Minimal ZIP writer for tests. Unlike normal tools it writes entry names verbatim,
 * so suites can craft hostile archives (../, absolute, symlink, bombs).
 */
export interface RawZipEntry {
  name: string;
  data?: Buffer | string;
  /** Unix mode for external attributes, e.g. 0o120777 for a symlink. */
  mode?: number;
  deflate?: boolean;
  encrypted?: boolean;
  /** Lie about uncompressed size in headers (for stream limit tests). */
  declaredSize?: number;
}

export function buildZip(entries: RawZipEntry[]): Buffer {
  const locals: Buffer[] = [];
  const centrals: Buffer[] = [];
  let offset = 0;
  for (const entry of entries) {
    const name = Buffer.from(entry.name, 'utf8');
    const raw = Buffer.isBuffer(entry.data) ? entry.data : Buffer.from(entry.data ?? '', 'utf8');
    const compressed = entry.deflate ? deflateRawSync(raw) : raw;
    // Traditional encryption prefixes a 12 byte header; mimic it so readers see a realistic entry.
    const body = entry.encrypted ? Buffer.concat([Buffer.alloc(12), compressed]) : compressed;
    const method = entry.deflate ? 8 : 0;
    const crc = crc32(raw) >>> 0;
    const size = entry.declaredSize ?? raw.length;
    const flags = 0x0800 | (entry.encrypted ? 0x1 : 0);
    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0);
    local.writeUInt16LE(20, 4);
    local.writeUInt16LE(flags, 6);
    local.writeUInt16LE(method, 8);
    local.writeUInt32LE(0, 10);
    local.writeUInt32LE(crc, 14);
    local.writeUInt32LE(body.length, 18);
    local.writeUInt32LE(size, 22);
    local.writeUInt16LE(name.length, 26);
    local.writeUInt16LE(0, 28);
    locals.push(local, name, body);
    const central = Buffer.alloc(46);
    central.writeUInt32LE(0x02014b50, 0);
    central.writeUInt16LE((3 << 8) | 20, 4);
    central.writeUInt16LE(20, 6);
    central.writeUInt16LE(flags, 8);
    central.writeUInt16LE(method, 10);
    central.writeUInt32LE(0, 12);
    central.writeUInt32LE(crc, 16);
    central.writeUInt32LE(body.length, 20);
    central.writeUInt32LE(size, 24);
    central.writeUInt16LE(name.length, 28);
    central.writeUInt16LE(0, 30);
    central.writeUInt16LE(0, 32);
    central.writeUInt16LE(0, 34);
    central.writeUInt16LE(0, 36);
    const mode = entry.mode ?? (entry.name.endsWith('/') ? 0o040755 : 0o100644);
    central.writeUInt32LE((mode << 16) >>> 0, 38);
    central.writeUInt32LE(offset, 42);
    centrals.push(central, name);
    offset += local.length + name.length + body.length;
  }
  const centralBuffer = Buffer.concat(centrals);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(entries.length, 8);
  end.writeUInt16LE(entries.length, 10);
  end.writeUInt32LE(centralBuffer.length, 12);
  end.writeUInt32LE(offset, 16);
  return Buffer.concat([...locals, centralBuffer, end]);
}
