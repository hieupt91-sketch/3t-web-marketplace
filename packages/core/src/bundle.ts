import { createHash } from 'node:crypto';
import { createReadStream, createWriteStream } from 'node:fs';
import { copyFile, mkdir, readFile, readdir, stat, writeFile } from 'node:fs/promises';
import { dirname, join, posix, relative, sep } from 'node:path';
import { ZipFile } from 'yazl';

/**
 * Generate a self-host bundle (docs/08 §6) from an immutable artifact tree, never
 * from a live runtime directory. Static adapters (static-html, vite-static) get
 * the served site files under site/ plus a static README. Runtime adapters
 * (node-http, next-standalone) get the runnable tree under app/ plus a
 * Dockerfile, docker-compose.yml, .env.example and a runtime README, so the
 * buyer can run the template on their own VPS with one command.
 */
export interface BundleMeta {
  slug: string;
  version: string;
  title: string;
  manifest: unknown;
  /** Third-party asset/license notice text (from the package or a default). */
  licenseNotice?: string;
}

interface RuntimeManifest {
  adapter?: string;
  runtime?: { entry?: string; port?: number; start?: string[]; healthPath?: string };
  database?: { engine?: string; fileName?: string; migrate?: string[]; seedDemo?: string[] };
  env?: { name?: string; scope?: string; required?: boolean; secret?: boolean; description?: string; defaultValue?: string }[];
  build?: { packageManager?: string };
}

function asManifest(value: unknown): RuntimeManifest {
  return (value ?? {}) as RuntimeManifest;
}

function isRuntimeAdapter(adapter: string | undefined): boolean {
  return adapter === 'node-http' || adapter === 'next-standalone';
}

async function listFiles(root: string, prefix = ''): Promise<string[]> {
  const out: string[] = [];
  for (const entry of await readdir(join(root, prefix), { withFileTypes: true })) {
    const rel = prefix ? posix.join(prefix, entry.name) : entry.name;
    if (entry.isDirectory()) out.push(...(await listFiles(root, rel)));
    else if (entry.isFile()) out.push(rel);
  }
  return out;
}

function readmeStatic(meta: BundleMeta): string {
  return [
    `# ${meta.title}`,
    '',
    `Slug: ${meta.slug}`,
    `Version: ${meta.version}`,
    '',
    'Static website bundle from Web Marketplace.',
    '',
    '## Contents',
    '- `site/` — the website files to serve with any static web server.',
    '- `template.manifest.json` — the template manifest.',
    '- `CHECKSUMS.txt` — SHA-256 of every file in `site/`.',
    '- `LICENSE-ASSETS.md` — third-party asset and license notices.',
    '',
    '## Run locally',
    'Serve the `site/` directory with a static server, for example:',
    '',
    '```bash',
    'cd site',
    'python3 -m http.server 8080',
    '```',
    '',
    'Then open http://localhost:8080 . Deploy `site/` to any static host (Nginx, Caddy, a CDN).',
    '',
    'This bundle contains no secrets, database or admin backend.',
    '',
  ].join('\n');
}

function validPort(value: unknown): number {
  return typeof value === 'number' && Number.isInteger(value) && value >= 1 && value <= 65535 ? value : 3000;
}

function startCommand(m: RuntimeManifest): string[] {
  if (Array.isArray(m.runtime?.start) && m.runtime!.start!.length > 0) return m.runtime!.start!.filter((s) => typeof s === 'string');
  if (typeof m.runtime?.entry === 'string' && m.runtime.entry) return ['node', m.runtime.entry];
  return ['node', 'server.js'];
}

function envName(value: unknown): string | null {
  return typeof value === 'string' && /^[A-Z][A-Z0-9_]*$/.test(value) ? value : null;
}

function installCommand(files: string[], m: RuntimeManifest): string | null {
  if (!files.includes('package.json')) return null;
  if (files.includes('pnpm-lock.yaml')) return 'corepack enable && pnpm install --prod --frozen-lockfile';
  if (files.includes('yarn.lock')) return 'yarn install --production --frozen-lockfile';
  if (files.includes('package-lock.json')) return 'npm ci --omit=dev';
  return 'npm install --omit=dev';
}

function dockerfile(meta: BundleMeta, m: RuntimeManifest, files: string[], port: number, start: string[]): string {
  const lines = [
    '# Generated by Web Marketplace — runtime self-host bundle.',
    'FROM node:22-alpine',
    'WORKDIR /app',
    'COPY app/ ./',
  ];
  const install = installCommand(files, m);
  if (install) lines.push(`RUN ${install}`);
  lines.push(
    'ENV NODE_ENV=production',
    `EXPOSE ${port}`,
    `CMD ${JSON.stringify(start)}`,
    '',
  );
  return lines.join('\n');
}

function composeFile(m: RuntimeManifest, port: number): string {
  const dbEngine = m.database?.engine;
  const lines = [
    '# Generated by Web Marketplace — run with: docker compose up -d --build',
    'services:',
    '  web:',
    '    build: .',
    '    ports:',
    `      - "${port}:${port}"`,
    '    env_file:',
    '      - .env',
    '    environment:',
    '      - NODE_ENV=production',
    `      - PORT=${port}`,
    '      - HOST=0.0.0.0',
  ];
  if (dbEngine === 'postgres') {
    lines.push('    depends_on:', '      - db');
  }
  const volumes: string[] = [];
  if (dbEngine === 'sqlite' && typeof m.database?.fileName === 'string') {
    const dir = posix.dirname(m.database.fileName);
    if (dir && dir !== '.') volumes.push(`      - appdata:/app/${dir}`);
  }
  if (volumes.length > 0) {
    lines.push('    volumes:', ...volumes);
  }
  lines.push('    restart: unless-stopped');
  if (dbEngine === 'postgres') {
    lines.push(
      '  db:',
      '    image: postgres:16-alpine',
      '    environment:',
      '      - POSTGRES_DB=appdb',
      '      - POSTGRES_USER=app',
      '      - POSTGRES_PASSWORD=app',
      '    volumes:',
      '      - pgdata:/var/lib/postgresql/data',
      '    restart: unless-stopped',
      'volumes:',
      '  pgdata:',
    );
    if (volumes.length > 0) lines.push('  appdata:');
  } else if (volumes.length > 0) {
    lines.push('volumes:', '  appdata:');
  }
  lines.push('');
  return lines.join('\n');
}

function envExample(m: RuntimeManifest, port: number): string {
  const lines = [
    '# Copy to .env and fill in the required values before starting.',
    '# Never commit a real .env file to version control.',
    `PORT=${port}`,
    'NODE_ENV=production',
  ];
  if (m.database?.engine === 'postgres') {
    lines.push('DATABASE_URL=postgres://app:app@db:5432/appdb');
    lines.push('# Change the database password in BOTH docker-compose.yml (POSTGRES_PASSWORD) and this DATABASE_URL.');
  }
  for (const item of m.env ?? []) {
    const name = envName(item?.name);
    if (!name) continue;
    if (item.description) lines.push(`# ${item.description}${item.required ? ' (required)' : ''}`);
    lines.push(`${name}=${item.secret ? '' : (item.defaultValue ?? '')}`);
  }
  lines.push('');
  return lines.join('\n');
}

function readmeRuntime(meta: BundleMeta, m: RuntimeManifest, port: number, start: string[]): string {
  const dbEngine = m.database?.engine;
  const lines = [
    `# ${meta.title}`,
    '',
    `Slug: ${meta.slug}`,
    `Version: ${meta.version}`,
    `Adapter: ${m.adapter}`,
    '',
    'Runtime website bundle from Web Marketplace.',
    '',
    '## Contents',
    '- `app/` — the runnable application files (no `node_modules`; dependencies are installed at deploy time).',
    '- `Dockerfile` — builds the application image.',
    '- `docker-compose.yml` — runs the application' + (dbEngine === 'postgres' ? ' and its PostgreSQL database' : '') + '.',
    '- `.env.example` — environment variables; copy it to `.env` and fill in the required values.',
    '- `template.manifest.json` — the template manifest.',
    '- `CHECKSUMS.txt` — SHA-256 of every file in `app/`.',
    '- `LICENSE-ASSETS.md` — third-party asset and license notices.',
    '',
    '## Quick start (Docker)',
    '',
    'Prerequisites: Docker and Docker Compose v2.',
    '',
    '```bash',
    'cp .env.example .env   # then edit .env and fill in the required values',
    'docker compose up -d --build',
    '```',
    '',
    `Then open http://localhost:${port} .`,
    '',
  ];
  if (dbEngine === 'postgres') {
    lines.push(
      'The `db` service creates an empty PostgreSQL database automatically.',
      'The default database password is `app`. To change it, change POSTGRES_PASSWORD in `docker-compose.yml` and DATABASE_URL in `.env` to the same new value.',
      'If the template ships database migrations, run them after the first start:',
      '',
    );
    for (const cmd of m.database?.migrate ?? []) lines.push('```bash', `docker compose exec web ${cmd}`, '```', '');
    if ((m.database?.migrate ?? []).length === 0) {
      lines.push('This template declares no migration commands.', '');
    }
  }
  if (dbEngine === 'sqlite') {
    lines.push(
      `The application database file (${m.database?.fileName ?? 'a SQLite file'}) is kept in a Docker volume, so it survives container rebuilds.`,
      '',
    );
  }
  const requiredEnv = (m.env ?? []).filter((e) => e.required && envName(e.name));
  if (requiredEnv.length > 0) {
    lines.push('## Required environment variables', '');
    for (const e of requiredEnv) lines.push(`- \`${e.name}\`${e.description ? ` — ${e.description}` : ''}`);
    lines.push('');
  }
  lines.push(
    '## Without Docker',
    '',
    'Prerequisites: Node.js 22.',
    '',
    '```bash',
    'cd app',
    'npm install --omit=dev   # or the install command for the template lockfile',
    `PORT=${port} HOST=0.0.0.0 NODE_ENV=production ${start.map((s) => (/\s/.test(s) ? `"${s}"` : s)).join(' ')}`,
    '```',
    '',
    '## Update to a newer version',
    '',
    'Download the newer bundle, replace the `app/` directory with the new one, keep your `.env` file and your data volumes, then run `docker compose up -d --build` again.',
    '',
    'This bundle contains no secrets. Fill in your own values in `.env`.',
    '',
  );
  return lines.join('\n');
}

/**
 * Demo-to-clean text transform for the "clean" download variant.
 *
 * The demo variant ships the template as-is (demo phone, demo labels).
 * The clean variant replaces the 3T demo phone with a fill-in
 * placeholder so buyers enter their real info before publishing:
 *  - inside data-en="..." attributes: "Your phone number";
 *  - everywhere else (visible text mirrors data-vi, comments and README
 *    prose are Vietnamese): "Số điện thoại của bạn";
 *  - leftover "(số demo)" / "(demo number)" markers are stripped;
 *  - stale demo-warning sentences that reference the 3T demo number are
 *    removed on a best-effort basis (wording varies across READMEs, so a
 *    warning without a trailing period may survive — it then mentions a
 *    placeholder, never a real number).
 * Deliberately NOT stripped: the SVG illustrations (artwork, not info),
 * sample prices/addresses/emails/hours (the template's base sample
 * content, already labelled as samples) — clean means "no demo phone",
 * not "empty page".
 */
const DEMO_PHONE_SPACED = '0967 136 099';
const DEMO_PHONE_PLAIN = '0967136099';
const VI_PHONE_PLACEHOLDER = 'Số điện thoại của bạn';
const EN_PHONE_PLACEHOLDER = 'Your phone number';

export function toCleanVariantText(text: string): string {
  let out = text.replace(/data-en="[^"]*"/g, (attr) =>
    attr
      .split(DEMO_PHONE_SPACED).join(EN_PHONE_PLACEHOLDER)
      .split(DEMO_PHONE_PLAIN).join(EN_PHONE_PLACEHOLDER)
      .replaceAll(' (demo number)', ''),
  );
  out = out.split(DEMO_PHONE_SPACED).join(VI_PHONE_PLACEHOLDER).split(DEMO_PHONE_PLAIN).join(VI_PHONE_PLACEHOLDER);
  out = out.replaceAll(' (số demo)', '').replaceAll(' (demo number)', '');
  out = out.replace(/[^.]*số demo của 3T[^.]*\./g, '');
  out = out.replace(/[^.]*demo number[^.]*3T[^.]*\./g, '');
  // CONFIG comments carry the demo phone in a parenthetical without a
  // trailing period ("(số demo của 3T — ...)"); rewrite it as a plain
  // fill-in instruction instead of leaving a stale fragment behind.
  out = out.replace(/\(số demo của 3T[^)]*\)/g, '(thay bằng số thật trước khi đăng)');
  out = out.replaceAll(`demo number ${VI_PHONE_PLACEHOLDER}`, EN_PHONE_PLACEHOLDER);
  return out;
}

/**
 * Copy an artifact tree to `destDir`, applying the clean-variant transform
 * to *.html and *.md files and copying everything else byte-for-byte.
 * The manifest version is unchanged: variant is a download option, not a
 * new version.
 */
export async function buildCleanSiteTree(srcDir: string, destDir: string): Promise<void> {
  await mkdir(destDir, { recursive: true });
  for (const file of await listFiles(srcDir)) {
    const src = join(srcDir, ...file.split('/'));
    const rel = relative(srcDir, src);
    if (rel.startsWith('..') || rel.includes(`..${sep}`)) continue;
    const dest = join(destDir, ...file.split('/'));
    await mkdir(dirname(dest), { recursive: true });
    if (file.endsWith('.html') || file.endsWith('.md')) {
      await writeFile(dest, toCleanVariantText(await readFile(src, 'utf8')), 'utf8');
    } else {
      await copyFile(src, dest);
    }
  }
}

/**
 * Write the bundle zip to `outPath`, streaming from `treeDir` (the artifact tree:
 * a static site tree for static adapters, a runnable tree for runtime adapters).
 * Returns the bundle's size and sha256.
 */
export async function buildSelfhostBundle(treeDir: string, outPath: string, meta: BundleMeta): Promise<{ size: number; sha256: string }> {
  const m = asManifest(meta.manifest);
  const runtime = isRuntimeAdapter(m.adapter);
  const prefix = runtime ? 'app' : 'site';
  const files = (await listFiles(treeDir)).sort();
  const zip = new ZipFile();
  const hash = createHash('sha256');
  const checksumLines: string[] = [];
  for (const file of files) {
    const full = join(treeDir, ...file.split('/'));
    // Guard against anything resolving outside the artifact tree.
    const rel = relative(treeDir, full);
    if (rel.startsWith('..') || rel.includes(`..${sep}`)) continue;
    const fileHash = await sha256Of(full);
    checksumLines.push(`${fileHash}  ${prefix}/${file}`);
    zip.addFile(full, `${prefix}/${file}`, { mtime: new Date(0), mode: 0o644 });
  }
  const manifestBuf = Buffer.from(JSON.stringify(meta.manifest, null, 2), 'utf8');
  zip.addBuffer(manifestBuf, 'template.manifest.json', { mtime: new Date(0) });
  if (runtime) {
    const port = validPort(m.runtime?.port);
    const start = startCommand(m);
    zip.addBuffer(Buffer.from(dockerfile(meta, m, files, port, start), 'utf8'), 'Dockerfile', { mtime: new Date(0) });
    zip.addBuffer(Buffer.from(composeFile(m, port), 'utf8'), 'docker-compose.yml', { mtime: new Date(0) });
    zip.addBuffer(Buffer.from(envExample(m, port), 'utf8'), '.env.example', { mtime: new Date(0) });
    zip.addBuffer(Buffer.from(readmeRuntime(meta, m, port, start), 'utf8'), 'README.md', { mtime: new Date(0) });
  } else {
    zip.addBuffer(Buffer.from(readmeStatic(meta), 'utf8'), 'README.md', { mtime: new Date(0) });
  }
  zip.addBuffer(Buffer.from(meta.licenseNotice ?? 'Third-party assets and licenses: see the template documentation.\n', 'utf8'), 'LICENSE-ASSETS.md', { mtime: new Date(0) });
  zip.addBuffer(Buffer.from(checksumLines.join('\n') + '\n', 'utf8'), 'CHECKSUMS.txt', { mtime: new Date(0) });
  zip.end();

  let size = 0;
  await new Promise<void>((resolve, reject) => {
    const out = createWriteStream(outPath, { flags: 'wx', mode: 0o600 });
    zip.outputStream
      .on('data', (chunk: Buffer) => {
        size += chunk.length;
        hash.update(chunk);
      })
      .on('error', reject)
      .pipe(out)
      .on('error', reject)
      .on('finish', resolve);
  });
  return { size, sha256: hash.digest('hex') };
}

function sha256Of(path: string): Promise<string> {
  return new Promise((resolve, reject) => {
    const hash = createHash('sha256');
    createReadStream(path)
      .on('data', (c) => hash.update(c))
      .on('error', reject)
      .on('end', () => resolve(hash.digest('hex')));
  });
}

